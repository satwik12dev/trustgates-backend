// ==========================================================
// Common Regular Expressions
// ==========================================================

const REGEX = Object.freeze({

    // ======================================================
    // Email
    // ======================================================

    EMAIL:

        /^[^\s@]+@[^\s@]+\.[^\s@]+$/,

    // ======================================================
    // Mobile Number (India)
    // ======================================================

    PHONE:

        /^[6-9]\d{9}$/,

    // ======================================================
    // Password
    // Minimum 8 chars
    // Uppercase
    // Lowercase
    // Number
    // Special Character
    // ======================================================

    PASSWORD:

        /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&#^()_\-+=])[A-Za-z\d@$!%*?&#^()_\-+=]{8,}$/,

    // ======================================================
    // Merchant Code
    // Example: MER000001
    // ======================================================

    MERCHANT_CODE:

        /^MER\d{6}$/,

    // ======================================================
    // Order ID
    // Example: ORD202607300001
    // ======================================================

    ORDER_ID:

        /^ORD[A-Za-z0-9_-]{6,50}$/,

    // ======================================================
    // Transaction ID
    // Example: TXN202607300001
    // ======================================================

    TRANSACTION_ID:

        /^TXN[A-Za-z0-9_-]{6,50}$/,

    // ======================================================
    // PAN Number
    // Example: ABCDE1234F
    // ======================================================

    PAN:

        /^[A-Z]{5}[0-9]{4}[A-Z]{1}$/,

    // ======================================================
    // Aadhaar
    // 12 Digits
    // ======================================================

    AADHAAR:

        /^[2-9]{1}[0-9]{11}$/,

    // ======================================================
    // GST Number
    // ======================================================

    GST:

        /^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[A-Z0-9]{3}$/,

    // ======================================================
    // IFSC Code
    // Example: HDFC0001234
    // ======================================================

    IFSC:

        /^[A-Z]{4}0[A-Z0-9]{6}$/,

    // ======================================================
    // Account Number
    // ======================================================

    ACCOUNT_NUMBER:

        /^[0-9]{9,18}$/,

    // ======================================================
    // UPI ID
    // Example: satwik@okhdfcbank
    // ======================================================

    UPI_ID:

        /^[a-zA-Z0-9.\-_]{2,256}@[a-zA-Z]{2,64}$/,

    // ======================================================
    // URL
    // ======================================================

    URL:

        /^(https?:\/\/)([\w.-]+)\.([a-z]{2,})(:\d+)?(\/.*)?$/i,

    // ======================================================
    // Domain
    // ======================================================

    DOMAIN:

        /^([a-zA-Z0-9-]+\.)+[a-zA-Z]{2,}$/,

    // ======================================================
    // UUID
    // Used for Idempotency Keys
    // ======================================================

    UUID:

        /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i,

    // ======================================================
    // Currency
    // Example: INR
    // ======================================================

    CURRENCY:

        /^[A-Z]{3}$/,

    // ======================================================
    // Amount
    // Example:
    // 100
    // 100.50
    // ======================================================

    AMOUNT:

        /^\d+(\.\d{1,2})?$/,

    // ======================================================
    // IP Address (IPv4)
    // ======================================================

    IPV4:

        /^(25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)(\.(25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)){3}$/,

    // ======================================================
    // API Public Key
    // Example:
    // pk_test_xxxxx
    // pk_live_xxxxx
    // ======================================================

    PUBLIC_KEY:

        /^pk_(test|live)_[A-Za-z0-9]{40,}$/,

    // ======================================================
    // API Secret Key
    // Example:
    // sk_test_xxxxx
    // sk_live_xxxxx
    // ======================================================

    SECRET_KEY:

        /^sk_(test|live)_[A-Za-z0-9]{40,}$/,

    // ======================================================
    // Webhook Secret
    // ======================================================

    WEBHOOK_SECRET:

        /^whsec_[A-Za-z0-9]{32,}$/,

    // ======================================================
    // Hex Signature
    // ======================================================

    SIGNATURE:

        /^[a-fA-F0-9]{64,128}$/

});

module.exports = {

    REGEX

};